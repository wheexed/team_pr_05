#include <stdio.h>  /* Подключаем printf() для вывода символов поля. */

#define WIDTH 80       /* Полная ширина поля вместе с границами. */
#define HEIGHT 25      /* Полная высота поля вместе с границами. */
#define RACKET_SIZE 3  /* Каждая ракетка занимает три строки. */

/* Эти переменные создаются в pong.c, а здесь только подключаются. */
extern int ball_x;          /* Горизонтальная координата мяча. */
extern int ball_y;          /* Вертикальная координата мяча. */
extern int left_racket_y;   /* Координата центра левой ракетки. */
extern int right_racket_y;  /* Координата центра правой ракетки. */
extern int left_score;      /* Счёт левого игрока. */
extern int right_score;     /* Счёт правого игрока. */

void draw_field(void)  /* Рисует состояние игры и ничего в нём не изменяет. */
{
    int x;  /* Номер текущего столбца: от 0 до 79. */
    int y;  /* Номер текущей строки: от 0 до 24. */

    printf("\nScore: %d : %d\n", left_score, right_score);  /* Выводим счёт. */

    y = 0;  /* Начинаем с верхней строки игрового поля. */
    while (y < HEIGHT)  /* Цикл создаёт ровно 25 строк. */
    {
        x = 0;  /* Каждую строку начинаем с её первого символа. */
        while (x < WIDTH)  /* Цикл создаёт ровно 80 символов в строке. */
        {
            if ((y == 0 || y == HEIGHT - 1) &&
                (x == 0 || x == WIDTH - 1))  /* Находим четыре угла. */
            {
                printf("+");  /* Печатаем угол игрового поля. */
            }
            else if (y == 0 || y == HEIGHT - 1)  /* Верхняя или нижняя строка. */
            {
                printf("-");  /* Печатаем горизонтальную стену. */
            }
            else if (x == 0 || x == WIDTH - 1)  /* Первый или последний столбец. */
            {
                printf("|");  /* Печатаем вертикальную стену. */
            }
            else if (x == ball_x && y == ball_y)  /* Координаты совпали с мячом. */
            {
                printf("o");  /* Мяч занимает ровно один символ. */
            }
            else if (x == 2 &&
                     y >= left_racket_y - RACKET_SIZE / 2 &&
                     y <= left_racket_y + RACKET_SIZE / 2)  /* Левая ракетка. */
            {
                printf("#");  /* Печатаем одну из трёх частей левой ракетки. */
            }
            else if (x == WIDTH - 3 &&
                     y >= right_racket_y - RACKET_SIZE / 2 &&
                     y <= right_racket_y + RACKET_SIZE / 2)  /* Правая ракетка. */
            {
                printf("#");  /* Печатаем одну из трёх частей правой ракетки. */
            }
            else if (x == WIDTH / 2 && y % 2 == 0)  /* Чётная строка центра. */
            {
                printf(":");  /* Печатаем видимую часть пунктирной линии. */
            }
            else  /* В текущей координате нет игрового объекта. */
            {
                printf(" ");  /* Пустую клетку изображаем пробелом. */
            }

            x = x + 1;  /* Переходим к следующему символу текущей строки. */
        }

        printf("\n");  /* Завершаем строку после вывода 80 символов. */
        y = y + 1;      /* Переходим к следующей строке игрового поля. */
    }
}
