#define WIDTH 80       /* Полная ширина игрового поля вместе с границами. */
#define HEIGHT 25      /* Полная высота игрового поля вместе с границами. */
#define RACKET_SIZE 3  /* Высота каждой ракетки в символах. */
#define WIN_SCORE 21   /* Количество очков, необходимое для победы. */

/* Эти обычные переменные создаются в pong.c и подключаются к этому файлу. */
extern int ball_x;          /* Горизонтальная координата мяча. */
extern int ball_y;          /* Вертикальная координата мяча. */
extern int ball_dx;         /* Направление мяча по горизонтали. */
extern int ball_dy;         /* Направление мяча по вертикали. */
extern int left_racket_y;   /* Координата центра левой ракетки. */
extern int right_racket_y;  /* Координата центра правой ракетки. */
extern int left_score;      /* Текущий счёт левого игрока. */
extern int right_score;     /* Текущий счёт правого игрока. */
extern int goal;            /* Результат последней проверки гола. */
extern int winner;          /* Номер победителя или 0, если его пока нет. */

void move_ball(void)  /* Перемещает мяч ровно на один игровой шаг. */
{
    ball_x = ball_x + ball_dx;  /* Сдвигаем мяч на одну клетку влево или вправо. */
    ball_y = ball_y + ball_dy;  /* Сдвигаем мяч на одну клетку вверх или вниз. */
}

void check_collision(void)  /* Проверяет столкновения со стенами и ракетками. */
{
    if (ball_y <= 1)  /* Проверяем внутреннюю сторону верхней стены. */
    {
        ball_y = 1;   /* Не разрешаем мячу оказаться внутри верхней границы. */
        ball_dy = 1;  /* После удара о верхнюю стену мяч движется вниз. */
    }
    else if (ball_y >= HEIGHT - 2)  /* Проверяем внутреннюю сторону нижней стены. */
    {
        ball_y = HEIGHT - 2;  /* Не разрешаем мячу оказаться внутри нижней границы. */
        ball_dy = -1;         /* После удара о нижнюю стену мяч движется вверх. */
    }

    if (ball_x == 2 && ball_dx < 0 &&  /* Мяч достиг столбца левой ракетки. */
        ball_y >= left_racket_y - RACKET_SIZE / 2 &&  /* Не выше ракетки. */
        ball_y <= left_racket_y + RACKET_SIZE / 2)    /* Не ниже ракетки. */
    {
        ball_dx = 1;  /* Отражаем мяч от левой ракетки вправо. */
    }
    else if (ball_x == WIDTH - 3 && ball_dx > 0 &&  /* Столбец правой ракетки. */
             ball_y >= right_racket_y - RACKET_SIZE / 2 &&  /* Не выше ракетки. */
             ball_y <= right_racket_y + RACKET_SIZE / 2)    /* Не ниже ракетки. */
    {
        ball_dx = -1;  /* Отражаем мяч от правой ракетки влево. */
    }
}

void check_goal(void)  /* Проверяет гол, изменяет счёт и возвращает мяч в центр. */
{
    goal = 0;  /* Перед новой проверкой сбрасываем результат прошлого хода. */

    if (ball_x <= 0)  /* Мяч достиг или пересёк левую границу поля. */
    {
        right_score = right_score + 1;  /* Правый игрок получает одно очко. */
        goal = 1;                       /* Запоминаем гол в левые ворота. */
    }
    else if (ball_x >= WIDTH - 1)  /* Мяч достиг или пересёк правую границу. */
    {
        left_score = left_score + 1;  /* Левый игрок получает одно очко. */
        goal = 2;                     /* Запоминаем гол в правые ворота. */
    }

    if (goal != 0)  /* Следующие действия нужны только после забитого гола. */
    {
        ball_x = WIDTH / 2;   /* Возвращаем мяч в центр по горизонтали. */
        ball_y = HEIGHT / 2;  /* Возвращаем мяч в центр по вертикали. */
        ball_dy = -ball_dy;   /* Чередуем вертикальное направление подачи. */

        if (goal == 1)  /* Если мяч вышел через левую сторону поля. */
        {
            ball_dx = 1;  /* Новая подача направляется вправо. */
        }
        else  /* Здесь goal равен 2: мяч вышел через правую сторону. */
        {
            ball_dx = -1;  /* Новая подача направляется влево. */
        }
    }
}

void check_winner(void)  /* Проверяет, достиг ли один из игроков 21 очка. */
{
    if (left_score == WIN_SCORE)  /* Проверяем победный счёт левого игрока. */
    {
        winner = 1;  /* Значение 1 обозначает победу левого игрока. */
    }
    else if (right_score == WIN_SCORE)  /* Проверяем счёт правого игрока. */
    {
        winner = 2;  /* Значение 2 обозначает победу правого игрока. */
    }
    else  /* Ни один игрок ещё не набрал необходимое количество очков. */
    {
        winner = 0;  /* Ноль сообщает main(), что игра должна продолжаться. */
    }
}
